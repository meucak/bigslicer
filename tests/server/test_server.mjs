import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createKatmanServer, isPrivateIp } from '../../server/server.mjs';

function makeBinaryCubeStl(size = 20) {
  const tris = [];
  const q = (a, b, c, d) => { tris.push([a, b, c]); tris.push([a, c, d]); };
  const s = size;
  q([0,0,0],[0,s,0],[s,s,0],[s,0,0]);
  q([0,0,s],[s,0,s],[s,s,s],[0,s,s]);
  q([0,0,0],[s,0,0],[s,0,s],[0,0,s]);
  q([s,s,0],[0,s,0],[0,s,s],[s,s,s]);
  q([0,s,0],[0,0,0],[0,0,s],[0,s,s]);
  q([s,0,0],[s,s,0],[s,s,s],[s,0,s]);
  const buf = Buffer.alloc(84 + tris.length * 50, 0);
  buf.write('katman-server-test', 0, 'ascii');
  buf.writeUInt32LE(tris.length, 80);
  for (let i = 0; i < tris.length; i++) {
    const off = 84 + i * 50 + 12;
    for (let v = 0; v < 3; v++) {
      buf.writeFloatLE(tris[i][v][0], off + v * 12);
      buf.writeFloatLE(tris[i][v][1], off + v * 12 + 4);
      buf.writeFloatLE(tris[i][v][2], off + v * 12 + 8);
    }
  }
  return buf;
}

describe('Katman Server API, Native C++20 Slicing & Security', () => {
  let server, baseUrl, tmpDir, libDir;
  const katmanBin = process.env.KATMAN_BIN || '/src/build/katman';

  before(async () => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'katman-srv-test-'));
    libDir = path.join(tmpDir, 'lib');
    fs.mkdirSync(libDir, { recursive: true });
    fs.writeFileSync(path.join(libDir, 'cube20.stl'), makeBinaryCubeStl(20));

    server = createKatmanServer({
      docsDir: path.resolve('docs'),
      dataDir: path.join(tmpDir, 'data'),
      katmanBin,
      libraryDirs: [{ label: 'TestLib', dir: libDir }],
    });
    await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
    const addr = server.address();
    baseUrl = `http://127.0.0.1:${addr.port}`;
  });

  after(async () => {
    await new Promise((resolve) => server.close(resolve));
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  it('blocks all private IPv4/IPv6 ranges against SSRF', () => {
    for (const ip of ['127.0.0.1', '10.0.0.1', '192.168.1.100', '172.16.0.1', '100.69.155.110', '169.254.169.254', '::1', 'fe80::1', '::ffff:127.0.0.1']) {
      assert.equal(isPrivateIp(ip), true, `Expected private IP blocked: ${ip}`);
    }
    assert.equal(isPrivateIp('1.1.1.1'), false);
    assert.equal(isPrivateIp('8.8.8.8'), false);
  });

  it('GET /api/health reports native C++20 slicer active', async () => {
    const r = await fetch(`${baseUrl}/api/health`);
    assert.equal(r.status, 200);
    const j = await r.json();
    assert.equal(j.ok, true);
    assert.equal(j.service, 'katman-slicer');
    assert.equal(j.nativeSlicer, true);
    assert.equal(j.libraryCount, 1);
  });

  it('GET /api/presets returns all printers, materials & qualities', async () => {
    const r = await fetch(`${baseUrl}/api/presets`);
    assert.equal(r.status, 200);
    const j = await r.json();
    assert.ok(j.printers.length >= 7);
    assert.ok(j.materials.length >= 6);
    assert.ok(j.qualities.length >= 5);
  });

  it('POST /api/slice runs native C++20 engine, returns stats + KTP1 + serves G-code', async () => {
    const stl = makeBinaryCubeStl(20);
    const cfg = { printer: 'bambu_p1s', material: 'pla', infill_pattern: 'gyroid', infill_density: 20 };
    const r = await fetch(`${baseUrl}/api/slice`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/octet-stream',
        'X-Filename': 'cube20.stl',
        'X-Slicer-Config': encodeURIComponent(JSON.stringify(cfg)),
      },
      body: stl,
    });
    assert.equal(r.status, 200);
    assert.equal(r.headers.get('x-engine'), 'native-cpp20');
    const jobId = r.headers.get('x-job-id');
    assert.match(jobId, /^[a-f0-9]{16}$/);

    const ab = await r.arrayBuffer();
    const dv = new DataView(ab);
    const jsonLen = dv.getUint32(0, true);
    const stats = JSON.parse(new TextDecoder().decode(new Uint8Array(ab, 4, jsonLen)));
    assert.ok(stats.layerCount >= 90);
    assert.ok(stats.filamentMm > 100);
    assert.ok(stats.printTimeSec > 30);

    // KTP1 magic check
    const ktp = new Uint8Array(ab, 4 + jsonLen);
    assert.equal(String.fromCharCode(ktp[0], ktp[1], ktp[2], ktp[3]), 'KTP1');

    // Fetch G-code preview & full download
    const gPrev = await fetch(`${baseUrl}/api/gcode/${jobId}?preview=4096`);
    assert.equal(gPrev.status, 200);
    const gTxt = await gPrev.text();
    assert.ok(gTxt.includes('; generated by Katman Slicer'));
    assert.ok(gTxt.includes(';LAYER:0'));
  });

  it('POST /api/slice/library slices directly from disk without upload', async () => {
    const r = await fetch(`${baseUrl}/api/slice/library`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ root: 0, path: 'cube20.stl', config: { infill_pattern: 'cubic', support_type: 'none' } }),
    });
    assert.equal(r.status, 200);
    assert.equal(r.headers.get('x-engine'), 'native-cpp20');
  });

  it('blocks path traversal and SSRF proxy attacks', async () => {
    const r1 = await fetch(`${baseUrl}/api/library/file?root=0&path=../../etc/passwd`);
    assert.equal(r1.status, 403);
    const r2 = await fetch(`${baseUrl}/api/proxy?url=http://127.0.0.1:8098/api/health`);
    assert.equal(r2.status, 403);
    const r3 = await fetch(`${baseUrl}/api/proxy?url=http://localhost/secret`);
    assert.equal(r3.status, 403);
  });
});
